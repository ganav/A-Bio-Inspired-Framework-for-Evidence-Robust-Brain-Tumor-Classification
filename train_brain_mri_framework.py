def validate_args(args: argparse.Namespace) -> None:
    if not args.data_root.is_dir():
        raise FileNotFoundError(
            f"--data-root not found: {args.data_root}"
        )
    if not args.mask_root.is_dir():
        raise FileNotFoundError(
            f"--mask-root not found: {args.mask_root}"
        )
    if not (0.0 < args.validation_fraction < 0.5):
        raise ValueError(
            "--validation-fraction must be between 0 and 0.5."
        )
    if args.blur_kernel <= 0 or args.blur_kernel % 2 == 0:
        raise ValueError(
            "--blur-kernel must be a positive odd integer."
        )
    if args.tile_grid <= 1:
        raise ValueError("--tile-grid must be > 1.")
    if not (0.0 <= args.cam_threshold < 1.0):
        raise ValueError(
            "--cam-threshold must be in [0, 1)."
        )
    if args.evaluate_only and args.weights_file is None:
        raise ValueError(
            "--weights-file is required with --evaluate-only."
        )


def main() -> None:
    args = build_parser().parse_args()
    validate_args(args)

    set_global_seed(args.seed)
    configure_gpu_memory_growth()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    class_names = tuple(args.classes)

    data_training = resolve_split_dir(
        args.data_root, "Training"
    )
    data_testing = resolve_split_dir(
        args.data_root, "Testing"
    )
    mask_training = resolve_split_dir(
        args.mask_root, "Training"
    )
    mask_testing = resolve_split_dir(
        args.mask_root, "Testing"
    )

    all_train_samples = collect_split_samples(
        data_training,
        mask_training,
        class_names,
    )
    test_samples = collect_split_samples(
        data_testing,
        mask_testing,
        class_names,
    )

    train_samples, val_samples = (
        stratified_train_validation_split(
            all_train_samples,
            validation_fraction=args.validation_fraction,
            seed=args.seed,
        )
    )

    print(
        f"Samples: train={len(train_samples)}, "
        f"validation={len(val_samples)}, "
        f"test={len(test_samples)}"
    )

    train_ds = build_dataset(
        train_samples,
        image_size=args.image_size,
        batch_size=args.batch_size,
        training=True,
        seed=args.seed,
        use_augmentation=not args.no_augmentation,
    )
    val_ds = build_dataset(
        val_samples,
        image_size=args.image_size,
        batch_size=args.batch_size,
        training=False,
        seed=args.seed,
        use_augmentation=False,
    )
    test_ds = build_dataset(
        test_samples,
        image_size=args.image_size,
        batch_size=args.batch_size,
        training=False,
        seed=args.seed,
        use_augmentation=False,
    )

    training_model, inference_model, classifier_layer = (
        build_models(
            backbone_name=args.backbone,
            image_size=args.image_size,
            num_classes=len(class_names),
            weights=args.weights,
            dropout=args.dropout,
        )
    )

    optimizer = tf.keras.optimizers.Adam(
        learning_rate=args.learning_rate
    )
    blur_kernel = gaussian_kernel(
        args.blur_kernel,
        args.blur_sigma,
    )

    trainer = EvidenceRobustTrainer(
        training_model=training_model,
        inference_model=inference_model,
        classifier_layer=classifier_layer,
        optimizer=optimizer,
        loss_weights=LossWeights(
            cam=args.lambda_cam,
            confidence=args.lambda_confidence,
            dominance=args.lambda_dominance,
        ),
        blur_kernel=blur_kernel,
        image_size=args.image_size,
        tile_grid=args.tile_grid,
        gradient_clip_norm=args.gradient_clip_norm,
        method=args.method,
    )

    config = vars(args).copy()
    for key in ("data_root", "mask_root", "output_dir", "weights_file"):
        if config.get(key) is not None:
            config[key] = str(config[key])
    config["classes"] = list(class_names)

    (args.output_dir / "configuration.json").write_text(
        json.dumps(config, indent=2),
        encoding="utf-8",
    )

    if args.evaluate_only:
        inference_model.load_weights(args.weights_file)
    else:
        train_model(
            trainer,
            train_ds,
            val_ds,
            epochs=args.epochs,
            output_dir=args.output_dir,
        )

    metrics = evaluate_model(
        trainer,
        test_ds,
        class_names=class_names,
        output_dir=args.output_dir,
        cam_threshold=args.cam_threshold,
        cam_examples=args.cam_examples,
    )

    print("\nTest results")
    for key, value in metrics.items():
        if isinstance(value, float):
            print(f"{key}: {value:.6f}")
        else:
            print(f"{key}: {value}")


if __name__ == "__main__":
    main()
