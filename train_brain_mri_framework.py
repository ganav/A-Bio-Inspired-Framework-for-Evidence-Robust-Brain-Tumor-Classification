#!/usr/bin/env python3
"""
Brain MRI version of the bio-inspired evidence-robust classification framework.

Dataset
-------
Designed for the Kaggle "Brain Tumor MRI Dataset" layout:

DATA_ROOT/
    Training/
        glioma/
        meningioma/
        notumor/
        pituitary/
    Testing/
        glioma/
        meningioma/
        notumor/
        pituitary/

The dataset itself does NOT provide brain-region masks. For the proposed method,
provide a separate MASK_ROOT with the same split/class/file layout:

MASK_ROOT/
    Training/
        glioma/
        meningioma/
        notumor/
        pituitary/
    Testing/
        glioma/
        meningioma/
        notumor/
        pituitary/

Each mask must be binary (brain region = white/1, non-brain = black/0) and must
have the same filename stem as its MRI image. Example:
    Training/glioma/Tr-gl_001.jpg
    masks/Training/glioma/Tr-gl_001.png

Training objective
------------------
Baseline:
    L = L_cls

Proposed:
    L = L_cls
        + lambda_cam * L_cam
        + lambda_confidence * L_confidence
        + lambda_dominance * L_dominance

1) L_cls:
   sparse categorical cross-entropy on the original MRI.

2) L_cam:
   CAM-based attention correction. Penalizes samples for which mean CAM
   activation outside the brain region exceeds mean activation inside it.

3) L_confidence:
   Three evidence-reduced inputs are created from the brain-masked image:
      - texture reduction: Gaussian blur (default 11 x 11)
      - shape disruption: 4 x 4 tile shuffle
      - intensity reduction: multiply brain pixels by 0.5
   For each perturbation, a target-class logit increase relative to the original
   image is penalized:
      relu(z_perturbed - z_original).

4) L_dominance:
   Uses the SAME three perturbed logits. The three target-logit drops are:
      d_k = z_original - z_k.
   Their within-sample variance is minimized to discourage dependence on a
   single evidence type.

At final inference, only the original MRI is required. No mask, perturbation,
or extra model is needed by the exported classifier.

Important research note
-----------------------
Masks generated by a heuristic, by manual editing, or by another algorithm
should not be described as "ground-truth" unless they are genuinely verified
ground-truth annotations.
"""

